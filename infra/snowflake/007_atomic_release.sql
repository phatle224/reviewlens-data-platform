  TO ROLE GOLD_BUILDER_ROLE;

CREATE VIEW IF NOT EXISTS REVIEWLENS.AUDIT.M3_RELEASE_SCHEMA_COMPATIBILITY
COMMENT = 'Constant M3 atomic-release contract marker; contains no source records'
AS
SELECT
  'IMP-M3-018-ATOMIC-RELEASE-V1'::VARCHAR(128) AS MIGRATION_ID,
  1::NUMBER(10, 0) AS SCHEMA_VERSION,
  2::NUMBER(10, 0) AS TABLE_COUNT,
  2::NUMBER(10, 0) AS PROCEDURE_COUNT;

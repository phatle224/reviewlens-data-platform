COMMENT = 'Constant M3 release-activation integrity contract marker; contains no source records'
AS
SELECT
  'IMP-M3-018-RELEASE-INTEGRITY-V1'::VARCHAR(128) AS MIGRATION_ID,
  28::NUMBER(10, 0) AS EXPECTED_OBJECT_REF_COUNT,
  2::NUMBER(10, 0) AS PROCEDURE_COUNT;
